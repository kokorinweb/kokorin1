/** Ссылка на WhatsApp с готовым текстом первого сообщения. */
export function whatsappUrl(text?: string): string {
  const base = `https://wa.me/${COMPANY.phoneDigits}`;
  return text ? `${base}?text=${encodeURIComponent(text)}` : base;
}

