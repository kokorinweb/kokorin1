/**
 * Цвета графиков админки.
 *
 * Палитра не подбиралась на глаз. Порядок слотов — механизм различимости при
 * дальтонизме: соседние пары проверены валидатором (худшая ΔE 9.1 при протанопии,
 * 19.6 при обычном зрении на белой поверхности). Переставлять слоты нельзя —
 * поедет то, что проверялось.
 *
 * Три слота (aqua, yellow, magenta) не дотягивают до контраста 3:1 к белому фону,
 * поэтому у доната обязательна легенда с подписями и числами — цвет там не
 * единственный канал.
 */
export const VIZ_SERIES = [
  "#2a78d6",
  "#eb6834",
  "#1baf7a",
  "#eda100",
  "#e87ba4",
  "#008300",
] as const;

/** Выручка по дням — один ряд, один цвет. Базилик из палитры ресторана. */
export const VIZ_BAR = "#2f5d3f";
export const VIZ_BAR_HOVER = "#23472f";

export function seriesColor(index: number): string {
  return VIZ_SERIES[index % VIZ_SERIES.length]!;
}
